TEST(TextureImportTest, DecodesPngAndReturnsBc7Texture) {
    QCE::ImageContainer container = QCE::ImageContainer::E_IMAGE_CONTAINER_JPEG;
    QCE::Texture2D texture;

    const auto status = QCE::import_texture(
        PNG_IMAGE.data(), PNG_IMAGE.size(), container, texture);

    ASSERT_EQ(status, QCE::ErrorCode::SUCCESS);
    EXPECT_EQ(container, QCE::ImageContainer::E_IMAGE_CONTAINER_PNG);
    EXPECT_EQ(texture.format, QCE::TextureFormat::E_TEXFMT_BC7_UNORM_BLOCK);
    EXPECT_EQ(texture.base_width, 1u);
    EXPECT_EQ(texture.base_height, 1u);
    ASSERT_EQ(texture.mip_levels.size(), 1u);
    EXPECT_EQ(texture.mip_levels[0].width, 1u);
    EXPECT_EQ(texture.mip_levels[0].height, 1u);
    EXPECT_EQ(texture.mip_levels[0].row_pitch, 16u);
    EXPECT_EQ(texture.mip_levels[0].slice_pitch, 16u);
    EXPECT_NE(texture.mip_levels[0].data, nullptr);
}

TEST(TextureImportTest, DecodesJpegAndGeneratesMipLevelsToSixteenPixels) {
    QCE::ImageContainer container = QCE::ImageContainer::E_IMAGE_CONTAINER_PNG;
    QCE::Texture2D texture;

    const auto status = QCE::import_texture(
        JPEG_IMAGE.data(), JPEG_IMAGE.size(), container, texture);

    ASSERT_EQ(status, QCE::ErrorCode::SUCCESS);
    EXPECT_EQ(container, QCE::ImageContainer::E_IMAGE_CONTAINER_JPEG);
    EXPECT_EQ(texture.format, QCE::TextureFormat::E_TEXFMT_BC7_UNORM_BLOCK);
    EXPECT_EQ(texture.base_width, 64u);
    EXPECT_EQ(texture.base_height, 32u);
    ASSERT_EQ(texture.mip_levels.size(), 3u);

    constexpr std::uint32_t expected_widths[] = { 64, 32, 16 };
    constexpr std::uint32_t expected_heights[] = { 32, 16, 8 };
    for (size_t level = 0; level < texture.mip_levels.size(); ++level) {
        const auto& mip = texture.mip_levels[level];
        EXPECT_EQ(mip.width, expected_widths[level]);
        EXPECT_EQ(mip.height, expected_heights[level]);
        EXPECT_EQ(mip.row_pitch, ((mip.width + 3) / 4) * 16);
        EXPECT_EQ(mip.slice_pitch, mip.row_pitch * ((mip.height + 3) / 4));
        EXPECT_NE(mip.data, nullptr);
    }
}

TEST(TextureImportTest, PreservesOutputsWhenInputIsInvalid) {
    QCE::ImageContainer container = QCE::ImageContainer::E_IMAGE_CONTAINER_JPEG;
    QCE::Texture2D texture;
    ASSERT_EQ(
        QCE::import_texture(PNG_IMAGE.data(), PNG_IMAGE.size(), container, texture),
        QCE::ErrorCode::SUCCESS);
    const auto* previous_mip_data = texture.mip_levels[0].data;
    const auto previous_format = texture.format;

    constexpr uint8_t invalid_data[] = { 0x00, 0x01, 0x02, 0x03 };
    const auto status = QCE::import_texture(
        invalid_data, sizeof(invalid_data), container, texture);

    EXPECT_EQ(status, QCE::ErrorCode::E_ENG_UNSUPPORTED_CONTAINER);
    EXPECT_EQ(container, QCE::ImageContainer::E_IMAGE_CONTAINER_PNG);
    EXPECT_EQ(texture.format, previous_format);
    ASSERT_EQ(texture.mip_levels.size(), 1u);
    EXPECT_EQ(texture.mip_levels[0].data, previous_mip_data);
}

TEST(TextureImportTest, SavesTextureAsKtx2AndLoadsItBack) {
    QCE::ImageContainer container = QCE::ImageContainer::E_IMAGE_CONTAINER_JPEG;
    QCE::Texture2D texture;
    ASSERT_EQ(
        QCE::import_texture(PNG_IMAGE.data(), PNG_IMAGE.size(), container, texture),
        QCE::ErrorCode::SUCCESS);
    ScopedTempFile output;

    ASSERT_EQ(
        QCE::save_texture_to_ktx2(texture, output.path),
        QCE::ErrorCode::SUCCESS);
    ASSERT_TRUE(std::filesystem::exists(output.path));

    QCE::Texture2D loaded_texture;
    ASSERT_EQ(QCE::texture2d_load(output.path, loaded_texture), QCE::ErrorCode::SUCCESS);
    EXPECT_EQ(loaded_texture.format, texture.format);
    EXPECT_EQ(loaded_texture.base_width, texture.base_width);
    EXPECT_EQ(loaded_texture.base_height, texture.base_height);
    ASSERT_EQ(loaded_texture.mip_levels.size(), texture.mip_levels.size());
    EXPECT_EQ(loaded_texture.mip_levels[0].width, texture.mip_levels[0].width);
    EXPECT_EQ(loaded_texture.mip_levels[0].height, texture.mip_levels[0].height);
}

TEST(TextureImportTest, RejectsTextureWithoutKtxBacking) {
    const QCE::Texture2D texture;
    const auto status = QCE::save_texture_to_ktx2(texture, "unused.ktx2");

    EXPECT_EQ(status, QCE::ErrorCode::E_ENG_BAD_ARG);
}
